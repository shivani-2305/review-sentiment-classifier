import google.generativeai as genai
genai.configure(api_key="YOUR_API_KEY_HERE")
model=genai.GenerativeModel("gemini-flash-latest")
def classify_review(review_text):
  prompt=f"""
Classify the review as Positive,Negative or Mixed
Review:"I loved the ambience and the food was good"
Sentiment:Positive
Review:"Worst experience and food was bad"
Sentiment:Negative
Review:"Food was good but service was slow"
Sentiment:Mixed
Review:"{review_text}"
Sentiment:
"""
  response=model.generate_content(prompt)
  return response.text
review1="the people are good and but this man was slow"
